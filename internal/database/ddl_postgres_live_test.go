package database

import (
	"context"
	"os"
	"strings"
	"testing"
)

/*
Postgres DDL against a real server.

Gated like the other integration tests, because it needs one:

	docker run -d --name devkit-pg-test -e POSTGRES_USER=devkit \
	  -e POSTGRES_PASSWORD=devkitpass -e POSTGRES_DB=devkitdb \
	  -p 5432:5432 postgres:17-alpine
	DEVKIT_PG_TEST=1 go test ./internal/database/ -run TestPostgresTableDDL

It is here rather than covered by a fake because the whole risk of this feature
lives in the catalogue queries: the reconstruction is only as right as
pg_attribute, pg_constraint and pg_index say it is, and no amount of mocking
can tell me whether a generated column comes back as a default.
*/
func TestPostgresTableDDL(t *testing.T) {
	if os.Getenv("DEVKIT_PG_TEST") != "1" {
		t.Skip("set DEVKIT_PG_TEST=1 to run the PostgreSQL DDL test")
	}
	ctx := context.Background()
	conn, err := postgresDriver{}.Dial(ctx, ConnConfig{
		Engine:   EnginePostgres,
		Host:     envOr("DEVKIT_PG_HOST", "127.0.0.1"),
		Port:     5432,
		Database: envOr("DEVKIT_PG_DB", "devkitdb"),
		Username: envOr("DEVKIT_PG_USER", "devkit"),
		Password: envOr("DEVKIT_PG_PASSWORD", "devkitpass"),
		SSLMode:  "disable",
	})
	if err != nil {
		t.Fatalf("Dial: %v", err)
	}
	defer conn.Close()

	fixture(t, ctx, conn)

	reader, ok := conn.(DDLReader)
	if !ok {
		t.Fatal("the postgres driver does not implement DDLReader")
	}
	ddl, err := reader.TableDDL(ctx, "ddltest", "ba_user")
	if err != nil {
		t.Fatalf("TableDDL: %v", err)
	}
	t.Logf("\n%s", ddl)

	for _, want := range []string{
		"CREATE TABLE ddltest.ba_user (",
		// An identity column is not a default, and saying DEFAULT here would
		// describe a column that can be written to.
		"id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL",
		// A serial IS a default, and the sequence it names has to survive.
		"legacy_id integer DEFAULT nextval(",
		// A generated column keeps its expression, and must not be printed as
		// a DEFAULT — the expression lives in the same catalogue slot.
		"email_lower text GENERATED ALWAYS AS (lower((email)::text)) STORED",
		"balance numeric(12,2) DEFAULT 0 NOT NULL",
		"tags text[] DEFAULT '{}'::text[]",
		"created_at timestamp with time zone DEFAULT now() NOT NULL",
		// A reserved word must come back quoted or the statement will not run.
		`"order" integer`,
		"CONSTRAINT ba_user_pkey PRIMARY KEY (id)",
		"CONSTRAINT ba_user_email_unique UNIQUE (email)",
		"CONSTRAINT ba_user_account_id_fkey FOREIGN KEY (account_id) REFERENCES ddltest.ba_account(id) ON DELETE CASCADE",
		"CONSTRAINT ba_user_balance_check CHECK ((balance >= (0)::numeric))",
		// Indexes follow the table, and a partial one keeps its WHERE.
		"CREATE INDEX ba_user_created_at_idx ON ddltest.ba_user USING btree (created_at DESC);",
		"WHERE (email IS NOT NULL);",
	} {
		if !strings.Contains(ddl, want) {
			t.Errorf("DDL is missing %q", want)
		}
	}

	// The index behind a constraint must not be printed as well, or the table
	// would define it twice.
	if strings.Contains(ddl, "CREATE UNIQUE INDEX ba_user_pkey") ||
		strings.Contains(ddl, "CREATE UNIQUE INDEX ba_user_email_unique") {
		t.Error("an index backing a constraint was printed a second time")
	}

	// The real proof: what comes back has to run.
	replay(t, ctx, conn, ddl)
}

func fixture(t *testing.T, ctx context.Context, conn Conn) {
	t.Helper()
	for _, statement := range []string{
		`DROP SCHEMA IF EXISTS ddltest CASCADE`,
		`CREATE SCHEMA ddltest`,
		`CREATE TABLE ddltest.ba_account (id bigserial PRIMARY KEY, code text NOT NULL UNIQUE)`,
		`CREATE TABLE ddltest.ba_user (
			id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			legacy_id   serial NOT NULL,
			account_id  bigint NOT NULL REFERENCES ddltest.ba_account(id) ON DELETE CASCADE,
			name        varchar(255) NOT NULL,
			email       varchar(255),
			email_lower text GENERATED ALWAYS AS (lower(email)) STORED,
			balance     numeric(12,2) NOT NULL DEFAULT 0,
			tags        text[] DEFAULT '{}'::text[],
			meta        jsonb NOT NULL DEFAULT '{}'::jsonb,
			created_at  timestamptz NOT NULL DEFAULT now(),
			"order"     integer,
			CONSTRAINT ba_user_email_unique UNIQUE (email),
			CONSTRAINT ba_user_balance_check CHECK (balance >= 0)
		)`,
		`CREATE INDEX ba_user_created_at_idx ON ddltest.ba_user (created_at DESC)`,
		`CREATE INDEX ba_user_name_lower_idx ON ddltest.ba_user (lower(name)) WHERE email IS NOT NULL`,
	} {
		exec(t, ctx, conn, statement)
	}
}

// replay runs the reconstruction into a fresh schema. A DDL that reads well and
// does not execute is the failure this whole feature has to avoid: it is the
// statement someone pastes into a migration.
func replay(t *testing.T, ctx context.Context, conn Conn, ddl string) {
	t.Helper()
	exec(t, ctx, conn, `DROP SCHEMA IF EXISTS ddlreplay CASCADE`)
	exec(t, ctx, conn, `CREATE SCHEMA ddlreplay`)
	// The foreign key points at the original schema, which still exists — the
	// point here is that every clause parses and applies, not that the copy is
	// standalone.
	for _, statement := range strings.Split(strings.ReplaceAll(ddl, "ddltest.ba_user", "ddlreplay.ba_user"), ";") {
		if strings.TrimSpace(statement) == "" {
			continue
		}
		exec(t, ctx, conn, statement)
	}
}

func exec(t *testing.T, ctx context.Context, conn Conn, statement string) {
	t.Helper()
	rows, err := conn.Query(ctx, statement)
	if err != nil {
		t.Fatalf("%s\n  -> %v", strings.TrimSpace(statement), err)
	}
	rows.Close()
}
