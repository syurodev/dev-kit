// Config wires the ports. Registry and Canonical are the same inputs
// harness.Resolve takes; every field except Canonical is required.
type Config struct {
	Store     Store
	Directory Directory
	Vendors   Vendors
	Policy    PolicySource
	Validator Validator
	Registry  func() harness.Registry
	Canonical func(string) (string, error)
	// Confirmer and Boundary are required by Apply. Audit is optional.
	Confirmer Confirmer
	Boundary  Boundary
	Audit     func(Event)
	// Live is optional. Without it nothing here reaches a running session.
	Live Live
}

// maxPending bounds the in-memory proposals. There is no timer: a proposal ends
// when it is applied, cancelled, refused or the process restarts.
const maxPending = 32

// Service prepares proposals. See the package comment.
type Service struct {
	cfg Config

	mu      sync.Mutex // guards pending only; never held across a port call
	pending map[string]*pendingProposal
}

func New(cfg Config) *Service {
	return &Service{cfg: cfg, pending: map[string]*pendingProposal{}}
}

type pendingProposal struct {
	id     string
	caller string
	req    Request // owned copy; Patch is normalized
	bound  evaluation
	view   View
	taken  bool // an apply is in flight or finished: single use
	// cancelled is set by Cancel, also while the person is deciding; committing
	// is set once the commit has started and can no longer be cancelled. Both
	// are guarded by Service.mu and checked right before the write.
	cancelled, committing bool
	abort                 context.CancelFunc // closes an open confirmation
}

// View is the host-authored confirmation content. Everything but
// RationaleUntrusted is generated by Go from the effective diff.
type View struct {
	Target            Target
	Tier              string
	Summary           string
	Changes           []ViewChange
	NeedsConfirmation bool
	// RationaleUntrusted is the proposer's own text. Display it labelled as
	// untrusted; it never influences anything above.
	RationaleUntrusted string
}

// ViewChange is one effect. Scope is ScopeStored for the saved configuration
// and ScopeRunning for the requester's running session; the two are never merged.
type ViewChange struct{ Vendor, Field, Key, Effect, Scope string }

const (
	ScopeStored  = "stored"
	ScopeRunning = "running"
)

// Prepared is what a proposer gets back. The ID is a lookup key held by this
// process for this caller; it is not an approval and proves nothing to anyone.
type Prepared struct {
	ID   string
	View View
}

type vendorDiff struct {
	Vendor         string
	VendorRevision int64
	FactsComplete  bool
	Before, After  string
	Tier           harness.Tier
	Changes        []harness.Change
}

// evaluation is everything an approval is bound to. A second evaluation of the
// same request must produce an equal digest or the proposal is stale.
type evaluation struct {
	Caller, SessionID, WorkspaceID string
	Target                         Target
	Patch                          Patch
	Rationale                      string
	Policy                         string
	W, S                           harness.Stamp
	Vendors                        []vendorDiff
	// Live is the effect on the requester's running session, judged from its
	// pinned launch V/W and durable S. nil: no active enforcing endpoint.
	Live *liveEffect
	// Tier is the strictest of the stored effects and the live effect.
	Tier harness.Tier

	write         harness.StoreWrite
	needsApproval bool
}

func (e evaluation) digest() string {
	b, _ := json.Marshal(e)
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// Prepare evaluates a request for the authenticated caller in ctx and keeps the
// result pending. It writes nothing and asks nobody.
func (s *Service) Prepare(ctx context.Context, req Request) (Prepared, error) {
	caller, ok := identity.FromContext(ctx)
	if !ok {
		return Prepared{}, ErrDenied
	}
	patch, err := req.Patch.normalized()
	if err != nil {
		return Prepared{}, err
	}
	owned := Request{WorkspaceID: req.WorkspaceID, SessionID: req.SessionID, Target: req.Target, Patch: patch, Rationale: cleanRationale(req.Rationale)}
	ev, policy, err := s.evaluate(ctx, caller, owned, s.liveReaderFor(ctx))
	if err != nil {
		return Prepared{}, err
	}
	if ev.Tier == harness.TierExecutable {
		if !policy.AllowExecutable {
			return Prepared{}, ErrExecutableDenied
		}
		// The prompt cannot yet show the exact command, arguments, paths and
		// env names. A truncated summary is not an approval.
		return Prepared{}, ErrExecutableNotReady
	}
	id, err := newID()
	if err != nil {
		return Prepared{}, err
	}
	view, err := buildView(ev, policy)
	if err != nil {
		return Prepared{}, err
	}
	p := &pendingProposal{id: id, caller: caller.String(), req: owned, bound: ev, view: view}
	s.mu.Lock()
	defer s.mu.Unlock()
	if len(s.pending) >= maxPending {
		return Prepared{}, ErrBusy
	}
	s.pending[id] = p
	return Prepared{ID: id, View: p.view}, nil
}

// Cancel withdraws a pending proposal. Only the caller that prepared it can. It
// also works while the person is being asked: the question is closed and the
// commit is refused. Once the commit has started it is too late, and Cancel says
// so instead of reporting a success that did not happen.
func (s *Service) Cancel(ctx context.Context, id string) error {
	caller, ok := identity.FromContext(ctx)
	s.mu.Lock()
	p := s.pending[id]
	if !ok || p == nil || p.caller != caller.String() {
		s.mu.Unlock()
		return ErrUnknownProposal
	}
	if p.committing {
		s.mu.Unlock()
		return ErrTooLateToCancel
	}
	p.cancelled = true
	delete(s.pending, id)
	abort := p.abort
	s.mu.Unlock()
	if abort != nil {
		abort()
	}
	return nil
}

// Pending is the number of proposals waiting (diagnostics and tests).
func (s *Service) Pending() int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return len(s.pending)
}

func newID() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(b[:]), nil
}

// evaluate resolves identity and every input from host data and computes the
// effective before and after with internal/harness. It is the only place a
// candidate is built, for Prepare and for the later revalidation alike.
func (s *Service) evaluate(ctx context.Context, caller identity.Caller, req Request, readLive liveReader) (evaluation, Policy, error) {
	ev := evaluation{Caller: caller.String(), Target: req.Target, Patch: req.Patch, Rationale: req.Rationale}
	var none Policy
	if req.Target != TargetSession && req.Target != TargetWorkspace {
		return ev, none, ErrInvalid
	}

	// Identity: from the authenticated caller and host data, never the request.
	var scope SessionScope
	switch {
	case caller.IsAgent():
		sc, err := s.cfg.Directory.SessionScope(ctx, caller.SessionID)
		if err != nil {
			return ev, none, ErrScopeGone
		}
		if (req.WorkspaceID != "" && req.WorkspaceID != sc.WorkspaceID) || (req.SessionID != "" && req.SessionID != caller.SessionID) {
			return ev, none, ErrDenied
		}
		if exists, err := s.cfg.Directory.WorkspaceExists(ctx, sc.WorkspaceID); err != nil || !exists {
			return ev, none, ErrScopeGone
		}
		scope, ev.SessionID = sc, caller.SessionID
	case caller.Kind == identity.KindUI:
		if req.WorkspaceID == "" {
			return ev, none, ErrInvalid
		}
		exists, err := s.cfg.Directory.WorkspaceExists(ctx, req.WorkspaceID)
		if err != nil || !exists {
			return ev, none, ErrScopeGone
		}
		scope.WorkspaceID = req.WorkspaceID
		if req.SessionID != "" {
			sc, err := s.cfg.Directory.SessionScope(ctx, req.SessionID)
			if err != nil {
				return ev, none, ErrScopeGone
			}
			if sc.WorkspaceID != req.WorkspaceID {
				return ev, none, ErrDenied
			}
			scope, ev.SessionID = sc, req.SessionID
		}
	default:
		// A terminal CLI, a remote person or an unknown origin cannot name a
		// target: fail closed.
		return ev, none, ErrDenied
	}
	ev.WorkspaceID = scope.WorkspaceID
	patch := req.Patch
	sessionEdit := len(patch.EnableGroups) > 0 || len(patch.RevokeGroups) > 0
	switch {
	case req.Target == TargetSession && (ev.SessionID == "" || patch.Workspace != nil || !sessionEdit):
		return ev, none, ErrInvalid
	case req.Target == TargetWorkspace && patch.Workspace == nil:
		return ev, none, ErrInvalid
	case sessionEdit && ev.SessionID == "":
		return ev, none, ErrInvalid
	}

	policy, err := s.cfg.Policy.Policy(ctx)
	if err != nil {
		return ev, none, ErrDenied
	}
	ev.Policy = policy.Revision

	w, wStamp, err := s.cfg.Store.GetProfile(ctx, ev.WorkspaceID)
	if err != nil {
		return ev, none, storeErr(err)
	}
	var o *harness.Override
	var oStamp harness.Stamp
	if ev.SessionID != "" {
		if o, oStamp, err = s.cfg.Store.GetOverride(ctx, ev.SessionID, ev.WorkspaceID); err != nil {
			return ev, none, storeErr(err)
		}
	}
	ev.W, ev.S = wStamp, oStamp

	// Candidates are built on copies; the request and the stored values are
	// never aliased.
	w2 := clone(w)
	wChanged := false
	if req.Target == TargetWorkspace {
		w2 = applyProfile(w, patch.Workspace)
		wChanged = !sameProfile(w, w2)
	}
	o2 := cloneOverride(o)
	oChanged := false
	if sessionEdit {
		o2 = applyOverride(o, patch.EnableGroups, patch.RevokeGroups)
		oChanged = !sameOverride(o, o2)
	}
	if wChanged {
		if err := s.cfg.Validator.Validate(ctx, *w2); err != nil {
			return ev, none, invalid(err)
		}
	}

	vendors := []string{scope.Vendor}
	if req.Target == TargetWorkspace {
		vendors = union(s.cfg.Vendors.Names(), vendors)
	}
	vendors = nonEmpty(vendors)
	needFacts := patch.touchesExecutableSurface()
	registry := s.cfg.Registry()
	for _, name := range vendors {
		vs, err := s.cfg.Vendors.State(ctx, name)
		if err != nil {
			return ev, none, ErrFactsUnavailable
		}
		if needFacts && !vs.FactsComplete {
			return ev, none, ErrFactsUnavailable
		}
		env := vs.Environment
		if !vs.FactsComplete {
			env = harness.Environment{} // not needed by this patch; see touchesExecutableSurface
		}
		before := harness.Inputs{Registry: registry, Vendor: vs.Vendor, Environment: env, Workspace: withRevision(w, wStamp.Revision), Session: overrideWithRevision(o, oStamp.Revision), Canonical: s.cfg.Canonical}
		after := before
		if wChanged {
			after.Workspace = withRevision(w2, wStamp.Revision+1)
		}
		if oChanged {
			after.Session = overrideWithRevision(o2, oStamp.Revision+1)
		}
		b, err := harness.Resolve(before)
		if err != nil {
			return ev, none, invalid(err)
		}
		a, err := harness.Resolve(after)
		if err != nil {
			return ev, none, invalid(err)
		}
		class := harness.Classify(b, a)
		if wChanged {
			// A change to W reaches every session of the workspace, including the
			// ones with no override of their own. The requesting session's S can
			// hide it (W turns git on while S already had it on), so W is judged
			// again with no session override on either side, and the stricter
			// tier of the two wins.
			wb, wa := before, after
			wb.Session, wa.Session = nil, nil
			rb, err := harness.Resolve(wb)
			if err != nil {
				return ev, none, invalid(err)
			}
			ra, err := harness.Resolve(wa)
			if err != nil {
				return ev, none, invalid(err)
			}
			class = mergeClassification(harness.Classify(rb, ra), class)
		}
		ev.Vendors = append(ev.Vendors, vendorDiff{Vendor: name, VendorRevision: vs.Vendor.Revision, FactsComplete: vs.FactsComplete,
			Before: b.Fingerprint, After: a.Fingerprint, Tier: class.Tier, Changes: class.Changes})
		if class.Tier > ev.Tier {
			ev.Tier = class.Tier
		}
	}

	// The running session. An S change reaches only the requester's endpoint, and
	// is judged under that endpoint's pinned launch V/W, which may differ from the
	// saved W in either direction: saved W can already enable a group that the
	// running session's W disables (a live widening with no stored difference), or
	// the reverse (a revoke that does nothing live). It is judged before the
	// no-change check for exactly that reason, and its tier joins the strictest.
	if oChanged && readLive != nil {
		lt, err := readLive(ev.SessionID)
		if err != nil {
			return ev, none, ErrLiveUnavailable
		}
		if lt.Active {
			le, class, err := liveEffectFor(lt, o, o2, oStamp)
			if err != nil {
				return ev, none, err
			}
			ev.Live = le
			if class.Tier > ev.Tier {
				ev.Tier = class.Tier
			}
		}
	}
	if ev.Tier == harness.TierNone {
		return ev, none, ErrNoChange
	}

	ev.write = harness.StoreWrite{WorkspaceID: ev.WorkspaceID}
	if wChanged {
		ev.write.Profile = &harness.ProfileWrite{Expect: wStamp, Value: w2}
	}
	if oChanged {
		ev.write.SessionID = ev.SessionID
		ev.write.Override = &harness.OverrideWrite{Expect: oStamp, Value: o2}
	}
	ev.needsApproval = ev.Tier != harness.TierNarrowing || !policy.AutoNarrowing
	return ev, policy, nil
}

// storeErr maps a store failure to a fixed refusal.
func storeErr(err error) error {
	switch {
	case errors.Is(err, harness.ErrStoreScope):
		return ErrScopeGone
	case errors.Is(err, harness.ErrStoreCorrupt):
		return ErrStoredUnreadable
	}
	return err
}

// ErrStoredUnreadable asks for a repair; it never falls back to defaults.
var ErrStoredUnreadable = &harness.Error{Code: harness.CodeProfileInvalid, Message: "The stored harness profile cannot be read. Repair or reset it in Settings."}

func withRevision(p *harness.Profile, revision int64) *harness.Profile {
	if p == nil {
		return nil
	}
	c := clone(p)
	c.Revision = revision
	return c
}

func overrideWithRevision(o *harness.Override, revision int64) *harness.Override {
	if o == nil {
		return nil
	}
	c := cloneOverride(o)
	c.Revision = revision
	return c
}

func sameProfile(a, b *harness.Profile) bool {
	if a == nil {
		a = &harness.Profile{Schema: harness.SchemaVersion}
	}
	if b == nil {
		b = &harness.Profile{Schema: harness.SchemaVersion}
	}
	x, y := *a, *b
	x.Revision, y.Revision = 0, 0
	xb, _ := json.Marshal(x)
	yb, _ := json.Marshal(y)
	return string(xb) == string(yb)
}

func sameOverride(a, b *harness.Override) bool {
	ga, gb := groupsOf(a), groupsOf(b)
	if len(ga) != len(gb) {
		return false
	}
	for i := range ga {
		if ga[i] != gb[i] {
			return false
		}
	}
	return true
}

func groupsOf(o *harness.Override) []string {
	if o == nil {
		return nil
	}
	g := append([]string(nil), o.Groups...)
	sort.Strings(g)
	return g
}

func union(a, b []string) []string {
	set := map[string]bool{}
	for _, s := range append(append([]string(nil), a...), b...) {
		set[s] = true
	}
	out := make([]string, 0, len(set))
	for s := range set {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func nonEmpty(in []string) []string {
	out := in[:0:0]
	for _, s := range in {
		if s != "" {
			out = append(out, s)
		}
	}
	return out
}

// mergeClassification keeps the strictest tier and every change of both, one
// entry per (field, key) at its higher tier.
func mergeClassification(a, b harness.Classification) harness.Classification {
	out := harness.Classification{Tier: a.Tier}
	if b.Tier > out.Tier {
		out.Tier = b.Tier
	}
	index := map[[2]string]int{}
	for _, c := range append(append([]harness.Change(nil), a.Changes...), b.Changes...) {
		k := [2]string{c.Field, c.Key}
		if i, ok := index[k]; ok {
			if c.Tier > out.Changes[i].Tier {
				out.Changes[i] = c
			}
			continue
		}
		index[k] = len(out.Changes)
		out.Changes = append(out.Changes, c)
	}
	sort.SliceStable(out.Changes, func(i, j int) bool {
		x, y := out.Changes[i], out.Changes[j]
		if x.Tier != y.Tier {
			return x.Tier > y.Tier
		}
		if x.Field != y.Field {
			return x.Field < y.Field
		}
		return x.Key < y.Key
	})
	return out
}
